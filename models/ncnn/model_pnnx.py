        v_70 = F.relu(input=v_69)
        v_71 = self.convbn2d_33(v_70)
        v_72 = (v_71 + v_68)
        v_73 = self.convbn2d_34(v_72)
        v_74 = F.relu(input=v_73)
        v_75 = self.convbn2d_35(v_74)
        v_76 = F.relu(input=v_75)
        v_77 = (v_76 + v_72)
        v_78, v_79 = F.adaptive_max_pool2d(input=v_77, output_size=(1,1), return_indices=True)
        v_80 = torch.flatten(input=v_78, end_dim=-1, start_dim=1)
        v_81 = self.linear_0(v_80)
        return v_81

